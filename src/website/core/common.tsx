// Shared website helpers: preview mode, visibility filters, global modal state.
import { useMemo } from 'react';
import { useSearchParams, Link, type LinkProps } from 'react-router-dom';
import { create } from 'zustand';
import type { Id, Institute, Lead, PublishStatus } from '../../data/types';
import { useStore } from '../../store';

/** True when ?preview=1 is in the URL — drafts become visible. */
export function usePreview() {
  const [sp] = useSearchParams();
  return sp.get('preview') === '1';
}

/** Is a record with this status visible on the website right now? */
export function useVisible() {
  const preview = usePreview();
  return (status: PublishStatus | string) => preview || status === 'published';
}

/** Link that keeps ?preview=1 when in preview mode. */
export function PLink({ to, ...p }: LinkProps & { to: string }) {
  const preview = usePreview();
  const target = preview && !to.includes('preview=1') ? `${to}${to.includes('?') ? '&' : '?'}preview=1` : to;
  return <Link to={target} {...p} />;
}

/** Published institutes (or all, in preview). */
export function useInstitutes() {
  const list = useStore((s) => s.db.institutes);
  const preview = usePreview();
  return useMemo(() => (preview ? list : list.filter((n) => n.status === 'published')), [list, preview]);
}

export function useCity(inst: Pick<Institute, 'cityId' | 'stateId'>) {
  const cities = useStore((s) => s.db.cities);
  const states = useStore((s) => s.db.states);
  const c = cities.find((x) => x.id === inst.cityId);
  const st = states.find((x) => x.id === inst.stateId);
  return [c?.name, st?.name].filter(Boolean).join(', ');
}

export const ownershipLabel = (o: Institute['ownership']) => ({ government: 'Government', private: 'Private', deemed: 'Deemed', public_private: 'Public-Private' })[o];

// ---- global modal state (Layout renders the modals) ----
export interface LeadIntent { source: Lead['source']; instituteId?: Id | null; title?: string; courseInterest?: string }
interface WebUi {
  authOpen: boolean;
  afterAuth: (() => void) | null;
  lead: LeadIntent | null;
  openAuth: (after?: () => void) => void;
  closeAuth: () => void;
  openLead: (intent: LeadIntent) => void;
  closeLead: () => void;
}
export const useWebUi = create<WebUi>((set) => ({
  authOpen: false,
  afterAuth: null,
  lead: null,
  openAuth: (after) => set({ authOpen: true, afterAuth: after ?? null }),
  closeAuth: () => set({ authOpen: false, afterAuth: null }),
  openLead: (lead) => set({ lead }),
  closeLead: () => set({ lead: null }),
}));

/** Generate a fake brochure file for an institute and trigger a download. */
export function downloadBrochure(inst: Institute, lines: string[]) {
  const body = [`${inst.name} (${inst.shortName})`, '='.repeat(40), `Established: ${inst.establishedYear}`, `Accreditation: ${inst.accreditation}`, `Website: ${inst.website}`, `Email: ${inst.email}`, `Phone: ${inst.phone}`, '', ...lines, '', 'Brochure generated by MSM Unify (prototype).'].join('\n');
  const a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob([body], { type: 'text/plain' }));
  a.download = `${inst.slug}-brochure-2026.txt`;
  a.click();
}

